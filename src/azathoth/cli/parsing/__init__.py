def build_parser() -> ArgumentParser:
    """Build the Azathoth command-line parser."""

    parser = ArgumentParser(
        prog="azathoth",
        description="Empirical optimization for context-aware AI workflows.",
    )

    parser.add_argument(
        "--version",
        action="version",
        version=f"%(prog)s {__version__}",
    )

    commands = parser.add_subparsers(
        dest=COMMAND_ATTRIBUTE,
    )

    add_workflow_parser(commands)

    add_run_parser(commands)

    add_experiment_parser(commands)

    add_invocation_parser(commands)

    add_model_parser(commands)

    add_judge_parser(commands)

    add_tool_parser(commands)

    add_benchmark_parser(commands)

    add_goal_parser(commands)

    add_init_parser(commands)
    add_job_parser(commands)

    return parser


